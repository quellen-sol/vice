func TestLocalCoordinates(t *testing.T) {
	ap := loadTestAirport(t)

	p := math.Point2LL{-99.97, 40.0}
	l := ap.Local(p)
	// float32 longitudes near 100 degrees are only good to ~7.6e-6
	// degrees, or ~3.5e-4nm.
	if math.Abs(l[1]) > 1e-5 || math.Abs(l[0]-0.015*ap.NMPerLongitude()) > 1e-3 {
		t.Errorf("Local: got %v", l)
	}
	if q := ap.FromLocal(l); math.Abs(q[0]-p[0]) > 1e-5 || math.Abs(q[1]-p[1]) > 1e-5 {
		t.Errorf("FromLocal(Local(p)): got %v, want %v", q, p)
	}

	// The 09/27 runway is 150' wide, running east-west.
	outline := ap.RunwayOutline(ap.Runways[0])
	width := ap.Distance(outline[0], outline[3]) * math.NauticalMilesToFeet
	if math.Abs(width-150) > 1 {
		t.Errorf("runway outline width: got %v ft, want 150", width)
	}
}

func TestEncodeDecode(t *testing.T) {
	ap := loadTestAirport(t)
	outline := ap.RunwayOutline(ap.Runways[0])
	ap.Polygons = []Polygon{{Kind: PolygonRunway, Rings: [][]math.Point2LL{outline[:]}}}

	var buf bytes.Buffer
	if err := ap.Encode(&buf); err != nil {
		t.Fatalf("Encode: %v", err)
	}
	ap2, err := Decode(&buf)
	if err != nil {
		t.Fatalf("Decode: %v", err)
	}
	if len(ap2.Nodes) != len(ap.Nodes) || len(ap2.Edges) != len(ap.Edges) || len(ap2.Polygons) != 1 ||
		ap2.Gates[0].Name != ap.Gates[0].Name || ap2.Edges[2].Zones[0].Kind != ZoneDeparture {
		t.Errorf("round trip mismatch: %+v", ap2)
	}
	// Derived state must be rebuilt so that routing works.
	if _, err := ap2.FindRoute(RouteRequest{From: 11, To: []NodeID{0}, Via: []string{"A"}}); err != nil {
		t.Errorf("FindRoute after decode: %v", err)
	}
}

func TestReadCRCASDEX(t *testing.T) {
	dir := t.TempDir()
	write := func(path, contents string) {
		path = filepath.Join(dir, path)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(contents), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("ARTCCs/ZXX.json", `{
	  "facility": {"id": "ZXX", "childFacilities": [
	    {"id": "T01", "childFacilities": [
	      {"id": "TST", "asdexConfiguration": {"videoMapId": "MAP1", "towerLocation": {"lat": 39.99, "lon": -99.99}}}
	    ]}
	  ]},
	  "videoMaps": [{"id": "MAP1", "name": "TST SAID"}]
	}`)
	write("VideoMaps/ZXX/MAP1.geojson", `{"type": "FeatureCollection", "features": [
	  {"type": "Feature", "properties": {"asdex": "runway"},
	   "geometry": {"type": "MultiPolygon", "coordinates": [[[[-100, 40], [-99.97, 40], [-99.97, 40.001], [-100, 40.001], [-100, 40]]]]}},
	  {"type": "Feature", "properties": {"asdex": "apron"},
	   "geometry": {"type": "Polygon", "coordinates": [
	     [[-99.99, 39.99], [-99.98, 39.99], [-99.98, 39.995], [-99.99, 39.995], [-99.99, 39.99]],
	     [[-99.988, 39.991], [-99.987, 39.991], [-99.987, 39.992], [-99.988, 39.991]]]}}
	]}`)

	a, err := ReadCRCASDEX(dir, "ZXX", "TST")
	if err != nil {
		t.Fatalf("ReadCRCASDEX: %v", err)
	}
	if a.MapName != "TST SAID" || a.TowerLocation != (math.Point2LL{-99.99, 39.99}) {
		t.Errorf("got map %q tower %v", a.MapName, a.TowerLocation)
	}
	if len(a.Polygons) != 2 {
		t.Fatalf("got %d polygons, want 2", len(a.Polygons))
	}
	if a.Polygons[0].Kind != PolygonRunway || len(a.Polygons[0].Rings) != 1 || len(a.Polygons[0].Rings[0]) != 4 {
		t.Errorf("runway polygon: got %+v", a.Polygons[0])
	}
	if a.Polygons[1].Kind != PolygonApron || len(a.Polygons[1].Rings) != 2 || len(a.Polygons[1].Rings[1]) != 3 {
		t.Errorf("apron polygon: got %+v", a.Polygons[1])
	}

	if _, err := ReadCRCASDEX(dir, "ZXX", "T01"); err == nil {
		t.Errorf("expected error for facility without ASDE-X")
	}
	if _, err := ReadCRCASDEX(dir, "ZXX", "NOPE"); err == nil {
		t.Errorf("expected error for missing facility")
	}
}

// TestKCOS checks the generated surface data for the pilot airport: every
// runway end can be reached from every gate, and each route ends by
// holding short of the departure runway.
func TestKCOS(t *testing.T) {
	ap, err := LoadAirport("KCOS")
	if err != nil {
		t.Fatalf("LoadAirport: %v", err)
	}
	if len(ap.Polygons) == 0 || len(ap.Gates) == 0 {
		t.Errorf("got %d polygons and %d gates", len(ap.Polygons), len(ap.Gates))
	}

	for _, end := range []string{"17L", "35R", "17R", "35L", "13", "31"} {
		entry, ok := ap.DepartureEntry(end)
		if !ok {
			t.Errorf("%s: no departure entry", end)
			continue
		}
		for _, g := range ap.Gates {
			from, ok := ap.GateNode(g)
			if !ok {
				t.Fatalf("%s: no gate node", g.Name)
			}
			r, err := ap.FindRoute(RouteRequest{From: from, To: []NodeID{entry}})
			if err != nil {
				t.Errorf("%s to %s: %v", g.Name, end, err)
				continue
			}
			if len(r.HoldShorts) == 0 || !slices.Contains(r.HoldShorts[len(r.HoldShorts)-1].RunwayEnds, end) {
				t.Errorf("%s to %s: route doesn't hold short of the runway: %+v", g.Name, end, r.HoldShorts)
			}
		}
	}
}
