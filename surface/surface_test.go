func TestRunwayConnections(t *testing.T) {
	ap := loadTestAirport(t)

	conns := ap.RunwayConnections("09")
	type conn struct {
		node    NodeID
		taxiway string
		right   bool
	}
	var got []conn
	for _, c := range conns {
		got = append(got, conn{c.Node, c.Taxiway, c.Right})
		if math.Abs(c.Angle-90) > 1 {
			t.Errorf("%s at node %d: angle %v, want 90", c.Taxiway, c.Node, c.Angle)
		}
	}
	// Heading east down 09, taxiways to the south are on the right.
	want := []conn{{0, "A1", true}, {1, "B", true}, {1, "B", false}, {2, "A3", true}}
	if !slices.Equal(got, want) {
		t.Errorf("connections: got %v, want %v", got, want)
	}
	if conns[0].Distance != 0 || math.Abs(conns[3].Distance-ap.Distance(ap.Nodes[0].Location, ap.Nodes[2].Location)) > 1e-4 {
		t.Errorf("unexpected connection distances %v and %v", conns[0].Distance, conns[3].Distance)
	}

	// From 27, everything is reversed.
	conns = ap.RunwayConnections("27")
	if conns[0].Node != 2 || conns[0].Right || conns[len(conns)-1].Node != 0 {
		t.Errorf("27 connections: got %+v", conns)
	}

	if n, ok := ap.DepartureEntry("09"); !ok || n != 0 {
		t.Errorf("09 departure entry: got %d, %v", n, ok)
	}
	if n, ok := ap.DepartureEntry("27"); !ok || n != 2 {
		t.Errorf("27 departure entry: got %d, %v", n, ok)
	}
	if _, ok := ap.DepartureEntry("18"); ok {
		t.Errorf("expected no departure entry for nonexistent runway")
	}
	if n, ok := ap.GateNode(ap.Gates[0]); !ok || n != 11 {
		t.Errorf("gate node: got %d, %v", n, ok)
	}
}

