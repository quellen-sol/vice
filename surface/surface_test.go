func loadTestAirport(t *testing.T) *Airport {
	t.Helper()
	ap, err := ParseAptDat(strings.NewReader(testAptDat), "KTST")
	if err != nil {
		t.Fatalf("ParseAptDat: %v", err)
	}
	return ap
}

func TestParseAptDat(t *testing.T) {
	ap := loadTestAirport(t)

	if ap.ElevationFt != 6000 {
		t.Errorf("elevation: got %v, want 6000", ap.ElevationFt)
	}
	if ap.Reference != (math.Point2LL{-99.985, 40}) {
		t.Errorf("reference: got %v", ap.Reference)
	}
	if ap.TowerLocation != (math.Point2LL{-99.99, 39.99}) {
		t.Errorf("tower location: got %v", ap.TowerLocation)
	}
	if len(ap.Nodes) != 12 || len(ap.Edges) != 13 {
		t.Fatalf("got %d nodes and %d edges, want 12 and 13", len(ap.Nodes), len(ap.Edges))
	}

	if len(ap.Runways) != 1 {
		t.Fatalf("got %d runways, want 1", len(ap.Runways))
	}
	rwy := ap.Runways[0]
	if rwy.Id() != "09/27" {
		t.Errorf("runway id: got %q", rwy.Id())
	}
	if math.Abs(rwy.WidthFt-150) > 0.1 {
		t.Errorf("runway width: got %v ft, want 150", rwy.WidthFt)
	}
	if math.Abs(rwy.Ends[1].DisplacedThresholdFt-100) > 0.1 {
		t.Errorf("27 displaced threshold: got %v ft, want 100", rwy.Ends[1].DisplacedThresholdFt)
	}

	e := ap.Edges[2] // 0-3 A1, in the active zone
	if e.Name != "A1" || e.WidthCode != "E" || e.Runway || len(e.Zones) != 2 {
		t.Errorf("edge 2: got %+v", e)
	}
	if got := e.ProtectedRunwayEnds(false); !slices.Equal(got, []string{"09", "27"}) {
		t.Errorf("edge 2 protected runway ends: got %v", got)
	}
	if !ap.Edges[0].Runway || ap.Edges[0].Name != "09/27" {
		t.Errorf("edge 0: got %+v", ap.Edges[0])
	}
	if ap.Edges[12].Name != "" {
		t.Errorf("unnamed edge: got name %q", ap.Edges[12].Name)
	}

	if len(ap.Gates) != 1 {
		t.Fatalf("got %d gates, want 1", len(ap.Gates))
	}
	g := ap.Gates[0]
	if g.Name != "Gate 1" || g.Kind != "gate" || g.SizeCode != "C" ||
		!slices.Equal(g.Types, []string{"jets", "turboprops"}) || !slices.Equal(g.Airlines, []string{"AAL", "UAL"}) {
		t.Errorf("gate: got %+v", g)
	}
}

func TestParseAptDatErrors(t *testing.T) {
	if _, err := ParseAptDat(strings.NewReader(testAptDat), "KZZZ"); err == nil {
		t.Errorf("expected error for missing airport")
	}
	if _, err := ParseAptDat(strings.NewReader(testAptDat), "KYYY"); err == nil {
		t.Errorf("expected error for airport without runways")
	}
	bad := strings.Replace(testAptDat, "1202 9 10 twoway", "1202 9 99 twoway", 1)
	if _, err := ParseAptDat(strings.NewReader(bad), "KTST"); err == nil {
		t.Errorf("expected error for edge with undefined node")
	}
}

func TestFindRoute(t *testing.T) {
	ap := loadTestAirport(t)

	tests := []struct {
		name           string
		req            RouteRequest
		wantNodes      []NodeID
		wantHoldShorts []HoldShort
		wantTaxiways   []string
	}{
		{
			name:           "gate to runway 09 via A",
			req:            RouteRequest{From: 11, To: []NodeID{0}, Via: []string{"A"}},
			wantNodes:      []NodeID{11, 5, 4, 3, 0},
			wantHoldShorts: []HoldShort{{Index: 3, RunwayEnds: []string{"09", "27"}}},
			wantTaxiways:   []string{"A", "A1"},
		},
		{
			name:           "gate to runway 27 via A",
			req:            RouteRequest{From: 11, To: []NodeID{2}, Via: []string{"a"}},
			wantNodes:      []NodeID{11, 5, 6, 7, 2},
			wantHoldShorts: []HoldShort{{Index: 3, RunwayEnds: []string{"09", "27"}}},
			wantTaxiways:   []string{"A", "A3"},
		},
		{
			// Crossing the runway on B gives a single hold short even though
			// it passes through two active-zone edges.
			name:           "cross the runway via B",
			req:            RouteRequest{From: 11, To: []NodeID{10}, Via: []string{"B"}},
			wantNodes:      []NodeID{11, 5, 8, 1, 9, 10},
			wantHoldShorts: []HoldShort{{Index: 2, RunwayEnds: []string{"09", "27"}}},
			wantTaxiways:   []string{"B"},
		},
		{
			name:           "runway edges are not used by default",
			req:            RouteRequest{From: 3, To: []NodeID{2}},
			wantNodes:      []NodeID{3, 4, 5, 6, 7, 2},
			wantHoldShorts: []HoldShort{{Index: 4, RunwayEnds: []string{"09", "27"}}},
		},
		{
			name:           "taxi down the runway when allowed",
			req:            RouteRequest{From: 3, To: []NodeID{2}, TaxiOnRunways: []string{"27"}},
			wantNodes:      []NodeID{3, 0, 1, 2},
			wantHoldShorts: []HoldShort{{Index: 0, RunwayEnds: []string{"09", "27"}}},
		},
		{
			name:           "runway named in via",
			req:            RouteRequest{From: 3, To: []NodeID{2}, Via: []string{"A1", "09"}},
			wantNodes:      []NodeID{3, 0, 1, 2},
			wantHoldShorts: []HoldShort{{Index: 0, RunwayEnds: []string{"09", "27"}}},
		},
		{
			// An arrival that exited at B is already on the runway, so
			// there's no hold short as it leaves.
			name:      "exit the runway to the gate",
			req:       RouteRequest{From: 1, To: []NodeID{11}, Via: []string{"B"}},
			wantNodes: []NodeID{1, 8, 5, 11},
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			r, err := ap.FindRoute(tc.req)
			if err != nil {
				t.Fatalf("FindRoute: %v", err)
			}
			if !slices.Equal(r.Nodes, tc.wantNodes) {
				t.Errorf("nodes: got %v, want %v", r.Nodes, tc.wantNodes)
			}
			if len(r.Edges) != len(r.Nodes)-1 {
				t.Errorf("got %d edges for %d nodes", len(r.Edges), len(r.Nodes))
			}
			if !slices.EqualFunc(r.HoldShorts, tc.wantHoldShorts, func(a, b HoldShort) bool {
				return a.Index == b.Index && slices.Equal(a.RunwayEnds, b.RunwayEnds)
			}) {
				t.Errorf("hold shorts: got %+v, want %+v", r.HoldShorts, tc.wantHoldShorts)
			}
			if tc.wantTaxiways != nil && !slices.Equal(r.Taxiways(ap), tc.wantTaxiways) {
				t.Errorf("taxiways: got %v, want %v", r.Taxiways(ap), tc.wantTaxiways)
			}
		})
	}
}

